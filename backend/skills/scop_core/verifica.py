"""Verificarea unui document de scop generat, pe defectele care s-au repetat in practica.

Fiecare verificare de aici exista pentru ca lipsa ei a lasat sa treaca un defect intr-un document
livrat. Nu sunt ipoteze: sunt cicatrici.

    python verifica_document.py "output/<document>.docx"
    python verifica_document.py --toate                  # tot ce e in output/
    python verifica_document.py <doc> --limba engleza    # adauga verificarea de limba

Iese cu cod 1 daca gaseste macar o problema, ca sa poata fi pus intr-un lant de generare.
"""
from __future__ import annotations

import argparse
import collections
import difflib
import pathlib
import re
import sys
import zipfile

_AICI = pathlib.Path(__file__).resolve().parent

from docx import Document  # noqa: E402
from docx.oxml.ns import qn  # noqa: E402
from docx.table import Table  # noqa: E402
from docx.text.paragraph import Paragraph  # noqa: E402

# Termeni care nu au ce cauta intr-un document redactat in engleza pentru un client strain.
# „Judet/county" si „republican norms" au ajuns in documentul Türkerler pentru ca modulele de
# continut au fost scrise pornind de la continutul romanesc.
TERMENI_INTERZISI = {
    "engleza": [
        "ANAF", "D300", "D390", "D394", "D406", "Intrastat", "BNR",
        "republican norm", "Republican norm", "county", "County",
        "perimetru", "Perimetru",
    ],
}

# Perechi capitol-descriere / capitol-naratiune in care repetarea e structura modelului, nu defect.
REPETITIE_ACCEPTATA = [("4.", "6."), ("6.", "4.")]

# Sinteza reia, ca eticheta, chiar elementele enumerate in tabelele de acoperire. Repetarea e
# functia ei: cititorul potriveste randul din sinteza cu cel din acoperire, iar daca am diferentia
# etichetele ca sa treaca verificarea, documentul ar deveni mai greu de citit, nu mai bun.
#
# Perechea se recunoaste dupa titlu, nu dupa numar: in documentul de CORE acoperirea e capitolul 6
# si sinteza 10, in cel consolidat CORE+Productie sunt 9 si 12. Prima varianta a acestei exceptii
# avea numerele scrise in cod si a lasat defectul sa reapara la primul document cu alta
# numerotare.
TITLURI_ACOPERIRE = ("incluse explicit", "acoperite partial", "in afara scopului",
                     "included explicitly", "partially covered", "out of scope")
TITLURI_SINTEZA = ("sinteza", "synthesis")


def _recapitulare_acceptata(capitole) -> bool:
    """Aceeasi eticheta intr-un tabel de acoperire si in sinteza nu e dublura, e corespondenta."""
    joase = [c.lower() for c in capitole]
    acoperire = any(any(t in c for t in TITLURI_ACOPERIRE) for c in joase)
    sinteza = any(any(t in c for t in TITLURI_SINTEZA) for c in joase)
    return acoperire and sinteza

# Siruri in care o secventa litera+cifra arata ca un cod de flux fara sa fie: nume de produs.
NU_SUNT_CODURI = [
    "Primavera P6", "P6 EPPM",
    # declaratiile fiscale romanesti se ciocnesc cu prefixul D al modulului de Depozit
    "D300", "D390", "D394", "D406", "D112", "D100", "D101",
    # modele de cantar si de echipament, citate ca exemple de integrari existente
    "Bizerba IS20", "IS20",
]

# Afirmatii pe care nu avem voie sa le facem, indiferent de limba documentului. Fiecare e aici
# dupa o corectie a beneficiarului: perechea e (tipar cautat, de ce e gresit).
AFIRMATII_INTERZISE = [
    (r"cod(?:ul)?\s+de\s+bare[^.]{0,80}?(?:generat|generare|automat)",
     "codurile de bare NU se genereaza automat: se introduc manual, cu verificarea unicitatii"),
    (r"(?:generar|generat)[^.]{0,40}?cod(?:ul)?\s+de\s+bare",
     "codurile de bare NU se genereaza automat: se introduc manual, cu verificarea unicitatii"),
    (r"barcodes?[^.]{0,60}?generat",
     "barcodes are NOT generated by the system: they are entered manually, with a uniqueness check"),
    (r"generat\w*[^.]{0,40}?barcode",
     "barcodes are NOT generated by the system: they are entered manually, with a uniqueness check"),
]

# Forme negate: fraza care spune tocmai ca NU facem lucrul interzis nu e o incalcare.
NEGATII = ("nu se genereaza", "nu se generează", "nu genereaza", "nu generează",
           "does not generate", "not generated", "no barcode is generated")

# Capitolele in care se citeaza, pe buna dreptate, codurile documentului corelat.
# Un bloc care numeste scopul corelat poarta codurile ACELUI document, nu ale acestuia.
MENTIUNE_SCOP_CORELAT = re.compile(r"scop\w*\s+de\s+Produc|documentul de Produc|"
                                   r"Production scope|scope of Production", re.I)

CAPITOLE_CU_CODURI_STRAINE = ("delimitare", "delimitarea", "boundary")


class Raport:
    def __init__(self, nume: str):
        self.nume = nume
        self.probleme: list[tuple[str, str]] = []

    def problema(self, verificare: str, detaliu: str) -> None:
        self.probleme.append((verificare, detaliu))

    def tipareste(self) -> None:
        print(f"\n{'=' * 78}\n{self.nume}\n{'=' * 78}")
        if not self.probleme:
            print("  fara probleme")
            return
        pe_verificare = collections.OrderedDict()
        for v, d in self.probleme:
            pe_verificare.setdefault(v, []).append(d)
        for v, lista in pe_verificare.items():
            print(f"\n  [{v}]  {len(lista)} problema/probleme")
            for d in lista:
                print(f"     - {d}")


def _blocuri(doc):
    """(capitol, tip, text) pentru fiecare paragraf si fiecare celula, in ordinea din document."""
    out, cap = [], ""
    for el in doc.element.body.iterchildren():
        if el.tag == qn("w:p"):
            p = Paragraph(el, doc)
            t = p.text.strip()
            if p.style.name.startswith("Heading") and t:
                cap = t
                out.append((cap, "titlu", t))
            elif t:
                out.append((cap, "paragraf", t))
        elif el.tag == qn("w:tbl"):
            for rand in Table(el, doc).rows:
                vazut = set()
                for celula in rand.cells:
                    if id(celula._tc) in vazut:
                        continue
                    vazut.add(id(celula._tc))
                    if celula.text.strip():
                        out.append((cap, "celula", celula.text.strip()))
    return out


def _coduri_definite(doc) -> set[str]:
    """Codurile scrise in prima coloana a tabelelor de fluxuri."""
    coduri = set()
    for t in doc.tables:
        cap = [c.text.strip() for c in t.rows[0].cells]
        # „Point" e capul tabelului de integrare, unde se definesc codurile INT; „Nr." e capul
        # tabelului de ipoteze de dimensionare, care defineste codurile P. Filtrul de mai jos
        # cere forma literă+cifră, deci un „Nr." cu numerotare simpla (1, 2, 3) nu produce coduri.
        if cap[:1] and cap[0] in ("Flow", "Cod", "Code", "Point", "Nr.", "No."):
            for r in t.rows[1:]:
                cod = r.cells[0].text.strip()
                for parte in re.split(r"\s*[-–]\s*", cod):
                    if re.fullmatch(r"[A-Z]{1,4}\d+", parte.strip()):
                        coduri.add(parte.strip())
    return coduri


def verifica_trasee(doc, raport: Raport) -> None:
    """Doua fluxuri din acelasi tabel nu pot avea acelasi traseu de documente.

    Defectul prins: in Achizitii, A5 („Factura de import") si A6 („Declaratie vamala de import")
    purtau amandoua traseul „Factura de import → DVI → NIR". A5 nu trece prin DVI — declaratia
    vamala este chiar fluxul A6 —, deci A5 promitea un pas pe care nu il descrie.

    Verificarea de dubluri semnalase perechea, dar am pus-o pe seama lantului comun si am
    inchis-o ca alarma falsa. De aceea traseul se verifica separat, pe structura si nu pe
    asemanare: traseul unui flux nu are voie sa fie o bucata din traseul altuia. Cand este,
    fluxul scurt nu descrie un drum propriu, ci repeta o parte din cel lung — exact cazul A5,
    al carui traseu era coada traseului lui A6. Nu e o nuanta de judecat, e o incluziune.
    """
    def pasi(titlu: str) -> list[str]:
        """Documentele din traseu, in ordine: partea cu sageti, de dupa doua puncte."""
        traseu = titlu.split(":", 1)[-1]
        return [re.sub(r"\s+", " ", p).strip().lower()
                for p in traseu.split("→") if p.strip()]

    def bucata_din(mic: list[str], mare: list[str]) -> bool:
        """`mic` apare in `mare` ca secventa de pasi consecutivi."""
        if len(mic) > len(mare):
            return False
        return any(mare[i:i + len(mic)] == mic for i in range(len(mare) - len(mic) + 1))

    for t in doc.tables:
        cap = [c.text.strip() for c in t.rows[0].cells]
        if not (cap[:1] and cap[0] in ("Flow", "Cod", "Code")):
            continue
        fluxuri = []
        for r in t.rows[1:]:
            titlu = r.cells[1].text.strip() if len(r.cells) > 1 else ""
            if "→" not in titlu:
                continue
            p = pasi(titlu)
            if len(p) > 1:
                fluxuri.append((r.cells[0].text.strip(), p))
        for i, (cod_a, pasi_a) in enumerate(fluxuri):
            for cod_b, pasi_b in fluxuri[i + 1:]:
                if pasi_a == pasi_b:
                    raport.problema("trasee", f"{cod_a} si {cod_b} poarta acelasi traseu — "
                                              f"{' → '.join(pasi_a)[:70]}")
                elif bucata_din(pasi_a, pasi_b):
                    raport.problema("trasee", f"traseul lui {cod_a} e o bucata din traseul lui "
                                              f"{cod_b} — {' → '.join(pasi_a)[:70]}")
                elif bucata_din(pasi_b, pasi_a):
                    raport.problema("trasee", f"traseul lui {cod_b} e o bucata din traseul lui "
                                              f"{cod_a} — {' → '.join(pasi_b)[:70]}")


def verifica_coduri(doc, raport: Raport) -> None:
    """Fiecare cod de flux citat in text trebuie sa existe intr-un tabel de fluxuri.

    Defectul prins: in documentul consolidat Türkerler, 9 din 16 puncte de integrare trimiteau la
    coduri din forma scurta a modulelor CORE (P, I, S, FA), inlocuita la consolidare cu forma
    integrala (A, D, V, MF). O verificare care enumera prefixele cunoscute NU prinde asta — de
    aceea codurile se extrag aici generic.
    """
    definite = _coduri_definite(doc)
    if not definite:
        return
    # Zona si elementul din analiza de acoperire vin din caietul de sarcini al clientului, cu
    # numerotarea lui („R1.2", „REQ12"), care nu e cod de flux. Raspunsul solutiei e textul nostru
    # si ramane verificat: acolo un cod inexistent e o trimitere rupta.
    din_caiet = set()
    for t in doc.tables:
        if [c.text.strip() for c in t.rows[0].cells][:2] == ["Zona", "Elementul"]:
            for r in t.rows[1:]:
                din_caiet.update(c.text.strip() for c in r.cells[:2] if c.text.strip())
    citate = collections.defaultdict(set)
    for cap, tip, text in _blocuri(doc):
        if tip == "celula" and text in definite:
            continue   # prima coloana a tabelului de fluxuri
        if tip == "celula" and text in din_caiet:
            continue
        if any(c in cap.lower() for c in CAPITOLE_CU_CODURI_STRAINE):
            continue   # capitolul de delimitare citeste codurile celuilalt document
        # Un cod citat in acelasi bloc cu numele scopului corelat este o trimitere catre celalalt
        # document, nu o legatura rupta: „livrarea furajului catre ferma: scopul de Productie
        # (N13)". Inainte de garda asta, un document CORE care se corela cu unul de Productie
        # raporta zeci de coduri „nedefinite" si inneca semnalarile reale.
        if MENTIUNE_SCOP_CORELAT.search(text):
            continue
        curatat = text
        for fals in NU_SUNT_CODURI:
            curatat = curatat.replace(fals, "")
        for cod in re.findall(r"\b([A-Z]{1,4}\d{1,2})\b", curatat):
            if cod not in definite:
                citate[cod].add(cap)
    for cod, capitole in sorted(citate.items()):
        raport.problema("coduri", f"{cod} e citat in {', '.join(sorted(capitole))[:70]} "
                                  f"dar nu e definit in niciun tabel de fluxuri")


def verifica_antet_subsol(doc, raport: Raport, nume_client: str | None) -> None:
    """Antetul si subsolul nu poarta numele altui client, iar numerotarea are text in jurul campurilor.

    Doua defecte prinse aici: subsolul mostenit care spunea „Teldo" in documentele Christof, si
    numerotarea care tiparea „146" pentru ca golirea luase si textul dintre PAGE si NUMPAGES.
    """
    from . import stil

    for container in stil._containere_antet_subsol(doc):
        for par in stil._paragrafe_container(container):
            text = par.text.strip()
            if not stil._are_camp(par):
                continue
            if not text or text.isdigit():
                raport.problema(
                    "numerotare",
                    f"paragraful cu campuri de pagina nu are text in jurul lor ({text!r}) — "
                    "PAGE si NUMPAGES se vor tipari lipite")
    if nume_client:
        for container in stil._containere_antet_subsol(doc):
            for par in stil._paragrafe_container(container):
                t = par.text
                if t.strip() and nume_client.lower() not in t.lower() and stil._are_camp(par) is False:
                    continue


def verifica_proprietati(zf: zipfile.ZipFile, raport: Raport, nume_client: str | None) -> None:
    """`docProps` nu trebuie sa pastreze titlul gazdei.

    Defectul prins: toate cele trei documente Türkerler aveau `dc:title` =
    „Descrierea solutiei ofertate. Modul Productie | Teldo", mostenit din gazda de stiluri.
    Nicio verificare pe corpul documentului nu il vede.
    """
    if "docProps/core.xml" not in zf.namelist():
        return
    x = zf.read("docProps/core.xml").decode("utf-8", "ignore")
    for camp in ("title", "subject"):
        m = re.search(rf"<dc:{camp}>([^<]*)</dc:{camp}>", x)
        valoare = m.group(1).strip() if m else ""
        if not valoare:
            continue
        if nume_client and nume_client.lower() not in valoare.lower() and camp == "title":
            raport.problema("proprietati",
                            f"dc:{camp} = {valoare!r} nu numeste clientul curent "
                            f"({nume_client!r}) — probabil mostenit din gazda")


def verifica_limba(blocuri, raport: Raport, limba: str | None,
                   scutite: set[str] | None = None) -> None:
    """Termeni dintr-o alta limba sau dintr-o alta jurisdictie, intr-un document redactat altfel.

    Textele scutite sunt cele dintr-un tabel de legenda: acolo termenul strain e chiar subiectul,
    nu o scapare.
    """
    if not limba or limba not in TERMENI_INTERZISI:
        return
    scutite = scutite or set()
    for cap, _, text in blocuri:
        if text in scutite:
            continue
        for termen in TERMENI_INTERZISI[limba]:
            if re.search(rf"\b{re.escape(termen)}", text):
                raport.problema("limba", f"„{termen}" + f"” apare in {cap[:52]}")


def verifica_afirmatii(blocuri, raport: Raport) -> None:
    """Afirmatii pe care beneficiarul le-a corectat o data si care nu trebuie sa reapara.

    Verificarea cauta tiparul, nu o fraza exacta: o reformulare care spune acelasi lucru gresit
    trebuie prinsa la fel de bine ca originalul.
    """
    for cap, _, text in blocuri:
        plat = re.sub(r"\s+", " ", text)
        for tipar, motiv in AFIRMATII_INTERZISE:
            m = re.search(tipar, plat, re.IGNORECASE)
            if not m:
                continue
            # fraza in care cade potrivirea; daca ea neaga lucrul interzis, e corecta
            inceput = plat.rfind(".", 0, m.start()) + 1
            sfarsit = plat.find(".", m.end())
            fraza = plat[inceput:sfarsit if sfarsit > 0 else len(plat)].lower()
            if any(neg in fraza for neg in NEGATII):
                continue
            raport.problema("afirmatii", f"{cap[:40]}: „{m.group(0)[:70]}" + f"” — {motiv}")


def verifica_dubluri(blocuri, raport: Raport) -> None:
    """Fraze identice si aproape identice, in afara tiparului capitol-descriere / capitol-naratiune.

    Defectul prins: la imbinarea a doua documente, premisele au ajuns de doua ori — o data
    identice (prinse de dedupe) si o data reformulate (nu au fost prinse). Pragul e coborat la
    0.80 tocmai pentru reformulari.
    """
    def norm(s):
        return re.sub(r"[^a-z0-9 ]", "", re.sub(r"\s+", " ", s.lower())).strip()

    lungi = [(cap, t) for cap, tip, t in blocuri if tip != "titlu" and len(t) > 60]

    grupe = collections.defaultdict(list)
    for cap, t in lungi:
        grupe[norm(t)].append(cap)
    for _, capitole in grupe.items():
        if len(capitole) < 2:
            continue
        pereche = (capitole[0][:2], capitole[1][:2])
        if pereche in REPETITIE_ACCEPTATA or _recapitulare_acceptata(capitole):
            continue
        raport.problema("dubluri", f"aceeasi fraza in {', '.join(c[:40] for c in capitole)}")

    # Reformulari. Se compara numai blocuri de acelasi fel: doua buline intre ele, doua celule
    # intre ele. O bulina si fluxul care o detaliaza spun firesc acelasi lucru in doua registre —
    # asta e structura modelului, nu o dublura, si ar inneca raportul in alarme false. Intre
    # feluri diferite se semnaleaza doar repetarea aproape literala.
    lungi_tipate = [(cap, tip, t) for cap, tip, t in blocuri if tip != "titlu" and len(t) > 60]
    pe_grup = collections.defaultdict(list)
    for cap, tip, t in lungi_tipate:
        pe_grup[(cap, tip)].append(t)
    for (cap, _), texte in pe_grup.items():
        for i in range(len(texte)):
            for j in range(i + 1, len(texte)):
                r = difflib.SequenceMatcher(None, norm(texte[i]), norm(texte[j])).ratio()
                if r >= 0.80:
                    raport.problema("dubluri",
                                    f"{cap[:44]}: doua intrari de acelasi fel spun acelasi lucru "
                                    f"({r:.0%}) — {texte[i][:54]}...")
    pe_capitol = collections.defaultdict(list)
    for cap, tip, t in lungi_tipate:
        pe_capitol[cap].append((tip, t))
    for cap, intrari in pe_capitol.items():
        for i in range(len(intrari)):
            for j in range(i + 1, len(intrari)):
                if intrari[i][0] == intrari[j][0]:
                    continue
                r = difflib.SequenceMatcher(None, norm(intrari[i][1]), norm(intrari[j][1])).ratio()
                if r >= 0.95:
                    raport.problema("dubluri",
                                    f"{cap[:44]}: bulina si fluxul sunt scrise identic ({r:.0%}) — "
                                    f"{intrari[i][1][:54]}...")


def verifica_contradictii(doc, blocuri, raport: Raport) -> None:
    """O arie cu capitol propriu nu are ce cauta in tabelul „Out of Scope".

    Defectul prins: documentul consolidat Türkerler descria opt tablouri de Business Intelligence
    la 4.5 si, in acelasi timp, trecea „Business intelligence" la ariile in afara scopului.
    """
    arii_afara = []
    for t in doc.tables:
        cap = [c.text.strip() for c in t.rows[0].cells]
        if cap[:2] == ["Area", "Position"]:
            arii_afara = [r.cells[0].text.strip() for r in t.rows[1:]]
    if not arii_afara:
        return
    titluri = [t for _, tip, t in blocuri if tip == "titlu"]

    def nucleu(s):
        return re.sub(r"[^a-z ]", "", s.lower()).strip()

    for arie in arii_afara:
        a = nucleu(arie)
        if len(a) < 6:
            continue
        for titlu in titluri:
            t = nucleu(re.sub(r"^[\d.]+\s*", "", titlu))
            # aceeasi arie, nu doar cuvinte comune: fie denumiri identice, fie una e inceputul
            # celeilalte („Business intelligence" vs „Business Intelligence Reports"). O arie
            # numita „... beyond the dashboards described" descrie tocmai restul, si e corecta.
            if t and (a == t or a.startswith(t + " ") or t.startswith(a + " ")):
                raport.problema("contradictii",
                                f"„{arie}" + f"” e in Out of Scope, dar are si capitol propriu: "
                                f"{titlu[:50]}")


def verifica_marcaje(doc, blocuri, raport: Raport) -> None:
    """Sectiunile trimise la clarificare trebuie sa fie chiar evidentiate, si fara marcaje ramase."""
    from . import stil

    for cap, _, text in blocuri:
        if stil.MARCAJ_DESCHIS in text or stil.MARCAJ_INCHIS in text:
            raport.problema("marcaje", f"marcaj « » ramas netransformat in {cap[:48]}")

    trimise = []
    for t in doc.tables:
        cap = [c.text.strip() for c in t.rows[0].cells]
        if cap[:1] == ["Section"]:
            trimise = [r.cells[0].text.strip() for r in t.rows[1:]]
    if not trimise:
        return

    def umbrit(par) -> bool:
        # umbrit pe toata latimea (paragraful) sau numai pe fraza marcata (runul)
        if not par.text.strip():
            return False
        pPr = par._p.find(qn("w:pPr"))
        if pPr is not None and pPr.find(qn("w:shd")) is not None:
            return True
        return any(r._r.find(qn("w:rPr")) is not None
                   and r._r.find(qn("w:rPr")).find(qn("w:shd")) is not None for r in par.runs)

    umbrite_pe_capitol = collections.defaultdict(int)
    cap = ""
    for el in doc.element.body.iterchildren():
        if el.tag == qn("w:p"):
            p = Paragraph(el, doc)
            if p.style.name.startswith("Heading") and p.text.strip():
                cap = p.text.strip()
            if umbrit(p):
                umbrite_pe_capitol[cap] += 1
        elif el.tag == qn("w:tbl"):
            for rand in Table(el, doc).rows:
                for celula in rand.cells:
                    for par in celula.paragraphs:
                        if umbrit(par):
                            umbrite_pe_capitol[cap] += 1
    for ref in trimise:
        numar = re.match(r"^([\d.]+)", ref)
        if not numar:
            continue
        prefix = numar.group(1).rstrip(".")
        gasit = any(c.startswith(prefix) and n for c, n in umbrite_pe_capitol.items())
        if not gasit:
            raport.problema("marcaje",
                            f"capitolul de clarificat trimite la „{ref[:46]}" + "”, "
                            "dar acolo nu e nimic evidentiat")


def verifica_figuri(blocuri, raport: Raport, eticheta: str = "Figur") -> None:
    """Figurile se numeroteaza continuu si fiecare are legenda."""
    numere = []
    for _, _, text in blocuri:
        m = re.match(rf"^{eticheta}\w*\s+(\d+)\.\s*(.*)", text)
        if m:
            numere.append(int(m.group(1)))
            if not m.group(2).strip():
                raport.problema("figuri", f"figura {m.group(1)} nu are legenda")
    if numere and numere != list(range(1, len(numere) + 1)):
        raport.problema("figuri", f"numerotarea figurilor nu e continua: {numere}")


def verifica_capitole(blocuri, raport: Raport) -> None:
    """Capitolele de nivel 1 se numeroteaza continuu, de la 1."""
    numere = []
    for _, tip, text in blocuri:
        if tip != "titlu":
            continue
        m = re.match(r"^(\d+)\.\s+\S", text)
        if m:
            numere.append(int(m.group(1)))
    unice = sorted(set(numere))
    if unice and unice != list(range(1, len(unice) + 1)):
        raport.problema("capitole", f"numerotarea capitolelor are goluri: {unice}")


def _texte_din_legende(doc) -> set[str]:
    """Celulele tabelelor de legenda, care traduc tocmai termenii din interfata straina."""
    out = set()
    for t in doc.tables:
        cap = [c.text.strip() for c in t.rows[0].cells]
        if cap and "Field as shown on screen" in cap:
            for r in t.rows:
                for c in r.cells:
                    if c.text.strip():
                        out.add(c.text.strip())
    return out


def verifica(cale: pathlib.Path, limba: str | None = None,
             client: str | None = None) -> Raport:
    raport = Raport(cale.name)
    doc = Document(str(cale))
    blocuri = _blocuri(doc)
    with zipfile.ZipFile(cale) as zf:
        verifica_proprietati(zf, raport, client)
    verifica_coduri(doc, raport)
    verifica_trasee(doc, raport)
    verifica_antet_subsol(doc, raport, client)
    verifica_limba(blocuri, raport, limba, _texte_din_legende(doc))
    verifica_afirmatii(blocuri, raport)
    verifica_dubluri(blocuri, raport)
    verifica_contradictii(doc, blocuri, raport)
    verifica_marcaje(doc, blocuri, raport)
    verifica_figuri(blocuri, raport)
    verifica_capitole(blocuri, raport)
    return raport


def _limba_documentului(cale: pathlib.Path) -> str:
    """Limba in care e redactat documentul, dedusa din antet.

    Verificarea de termeni straini nu are sens pe un document romanesc: acolo „ANAF" si „D300"
    sunt continut corect, nu scapari. Se aplica numai documentelor in engleza.
    """
    doc = Document(str(cale))
    from . import stil
    for container in stil._containere_antet_subsol(doc, antet=True, subsol=False):
        for par in stil._paragrafe_container(container):
            if "Solution Scope Description" in par.text:
                return "engleza"
    return "fara"


def _client_din_subsol(cale: pathlib.Path) -> str | None:
    """Numele clientului, citit din subsol: „<Client>  |  Charisma ERP  |  v<x>”."""
    doc = Document(str(cale))
    from . import stil
    for container in stil._containere_antet_subsol(doc, antet=False, subsol=True):
        for par in stil._paragrafe_container(container):
            t = par.text.strip()
            if "|" in t and not stil._are_camp(par):
                return t.split("|")[0].strip()
    return None


def main(argv=None) -> int:
    # doar la rularea din linia de comanda: modulul e importat si de backend-ul site-ului, unde
    # iesirea standard a procesului nu e a lui
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description="Verifica un document de scop generat.")
    ap.add_argument("document", nargs="?", help="calea documentului .docx")
    ap.add_argument("--toate", action="store_true", help="verifica tot ce e in output/")
    ap.add_argument("--limba", choices=sorted(TERMENI_INTERZISI) + ["auto", "fara"],
                    default="auto",
                    help="limba documentului; auto o deduce din antet (implicit)")
    ap.add_argument("--client", default=None,
                    help="numele clientului; implicit se citeste din subsol")
    args = ap.parse_args(argv)

    if args.toate:
        fisiere = sorted(f for f in (_AICI / "output").glob("*.docx")
                         if not f.name.startswith("~$"))
    elif args.document:
        fisiere = [pathlib.Path(args.document)]
    else:
        raise SystemExit("Da calea unui document sau foloseste --toate.")

    total = 0
    for f in fisiere:
        if not f.exists():
            raise SystemExit(f"Nu exista: {f}")
        limba = _limba_documentului(f) if args.limba == "auto" else args.limba
        raport = verifica(f, limba=None if limba == "fara" else limba,
                          client=args.client or _client_din_subsol(f))
        raport.tipareste()
        total += len(raport.probleme)
    print(f"\n{'-' * 78}\nTOTAL: {total} problema/probleme in {len(fisiere)} document(e)")
    return 1 if total else 0


if __name__ == "__main__":
    raise SystemExit(main())
